/**
 * Turning a paperwork config into project files.
 *
 * Planning and writing are separate on purpose: what the maker would touch is
 * knowable without moving anything, so a preview and the write it precedes are
 * one code path.
 *
 * A division is either new (it gets a page and a sidebar entry) or one the app
 * already declares (its paperwork gets `/divisions/<slug>/paperwork` and a
 * sidebar entry of its own, because overwriting a hand-written page would delete
 * it). Several divisions can be generated; every emitted file is rebuilt from
 * all the configs on disk, so adding one never drops another.
 */

import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

import { DIVISIONS, ROLES, type Division } from "@/configs/roles";
import { GENERATED_DIVISIONS } from "@/configs/generated/divisions";
import {
  divisionRoute,
  divisionSlug,
  validatePaperworkConfig,
  type PaperworkConfig,
} from "./schema";

/** Where a division's emblem lives: the maker offers these by name. */
export const EMBLEM_DIRECTORY = "public/Division";

export const GENERATED_PAPERWORK_DIR = "src/app/constants/paperwork/generated";
export const GENERATED_DIVISIONS_FILE = "src/configs/generated/divisions.ts";
export const GENERATED_DIVISION_PAGES_FILE =
  "src/app/constants/divisions/generated.ts";

export type PlannedFileAction = "create" | "update" | "unchanged";

export type PlannedFile = {
  path: string;
  content: string;
  /** The file as it is now, when it exists - what a diff is built from. */
  before?: string;
  action: PlannedFileAction;
};

export type PaperworkPlan = {
  ok: boolean;
  problems: string[];
  files: PlannedFile[];
  /** The edits that wire generated content into the app (one-time, by hand). */
  integration: string[];
};

/** Every path this tool may write, relative to the repository root. */
const ALLOWED_PATHS = new Set([
  GENERATED_DIVISIONS_FILE,
  GENERATED_DIVISION_PAGES_FILE,
]);

function isAllowedPath(file: string): boolean {
  return (
    ALLOWED_PATHS.has(file) ||
    /^src\/app\/constants\/paperwork\/generated\/[a-z][a-zA-Z0-9]*\.json$/.test(
      file,
    ) ||
    /^src\/app\/constants\/paperwork\/generated\/index\.ts$/.test(file) ||
    /^src\/app\/\(routes\)\/divisions\/[a-z0-9-]+\/page\.tsx$/.test(file) ||
    /^src\/app\/\(routes\)\/divisions\/[a-z0-9-]+\/paperwork\/page\.tsx$/.test(
      file,
    )
  );
}

async function readFromRoot(
  root: string,
  file: string,
): Promise<string | undefined> {
  try {
    return await readFile(path.join(root, file), "utf8");
  } catch {
    return undefined;
  }
}

async function existingGeneratedKeys(root: string): Promise<string[]> {
  try {
    const entries = await readdir(path.join(root, GENERATED_PAPERWORK_DIR));
    return entries
      .filter((entry) => entry.endsWith(".json"))
      .map((entry) => entry.replace(/\.json$/, ""))
      .sort();
  } catch {
    return [];
  }
}

function fileAction(
  before: string | undefined,
  content: string,
): PlannedFileAction {
  if (before === undefined) return "create";
  return before === content ? "unchanged" : "update";
}

function serialiseConfig(config: PaperworkConfig): string {
  return `${JSON.stringify(config, null, 2)}\n`;
}

function aggregatorContent(keys: readonly string[]): string {
  const imports = keys
    .map((key) => `import ${key} from "./${key}.json";`)
    .join("\n");
  const entries = keys.map((key) => `  ${key} as PaperworkConfig,`).join("\n");
  return `// Generated by the Paperwork Maker. Do not edit by hand.
import type { PaperworkConfig } from "@/lib/paperwork/schema";

${imports}

/** Every generated division's paperwork, in generated-file order. */
export const GENERATED_PAPERWORK: readonly PaperworkConfig[] = [
${entries}
];
`;
}

function pageContent(config: PaperworkConfig, key: string): string {
  return `// Generated by the Paperwork Maker. Do not edit by hand.
import type { Metadata } from "next";

import { PaperworkWorkspace } from "@/components/paperwork/paperwork-workspace";
import { PageContainer } from "@/components/ui/page-container";
import type { PaperworkConfig } from "@/lib/paperwork/schema";

import config from "@/app/constants/paperwork/generated/${key}.json";

export const metadata: Metadata = {
  title: ${JSON.stringify(config.division.label)},
  description: ${JSON.stringify(config.division.description)},
};

export default function Page() {
  // The same container every division page sits in: the workspace draws the
  // heading and the builder, not the page's width or margins.
  return (
    <PageContainer>
      <PaperworkWorkspace config={config as PaperworkConfig} />
    </PageContainer>
  );
}
`;
}

type GeneratedTarget = {
  /** This config is the division's own page, not a tab beside one. */
  isNew: boolean;
  /** Whether the maker also declares the division, or only gives it a page. */
  ownsDeclaration: boolean;
  route: string;
  pagePath: string;
};

/** Where one config's page goes, without touching anything. */
function targetFor(config: PaperworkConfig): GeneratedTarget {
  const key = config.division.key;
  const declared = (DIVISIONS as Record<string, Division>)[key];
  const generated = (GENERATED_DIVISIONS as Record<string, Division>)[key];
  // A hand-written division declares its route once it has a page. One with no
  // route has none, so its paperwork is the page - hanging it off a parent that
  // does not exist would leave the division listed with nothing behind it.
  const handWritten = Boolean(declared && !generated);
  const base = handWritten ? declared.route?.replace(/\/+$/, "") : undefined;

  if (base) {
    // The division already has a hand-written page: this one is the division's
    // paperwork tab, so the two never compete for the same file.
    return {
      isNew: false,
      ownsDeclaration: false,
      route: `${base}/paperwork`,
      pagePath: `src/app/(routes)/divisions/${divisionSlug(key)}/paperwork/page.tsx`,
    };
  }

  return {
    isNew: true,
    // The ranks and membership of a division declared by hand stay where they
    // are: the maker only owns divisions it introduced itself.
    ownsDeclaration: !handWritten,
    route: handWritten
      ? divisionRoute(key)
      : (generated?.route ?? divisionRoute(key)),
    pagePath: `src/app/(routes)/divisions/${divisionSlug(key)}/page.tsx`,
  };
}

type GeneratedDivisionEntry = {
  key: string;
  label: string;
  route: string;
  icon?: string;
  membershipAlias?: string;
  ranks: string[];
};

type GeneratedPageEntry = {
  key: string;
  label: string;
  route: string;
  icon?: string;
};

function generatedRoles(configs: readonly PaperworkConfig[]): {
  roles: { alias: string; name: string; id: string }[];
  divisions: GeneratedDivisionEntry[];
  paperworkPages: GeneratedPageEntry[];
} {
  const roles: { alias: string; name: string; id: string }[] = [];
  const divisions: GeneratedDivisionEntry[] = [];
  const paperworkPages: GeneratedPageEntry[] = [];

  for (const config of configs) {
    const division = config.division;
    const target = targetFor(config);

    if (!target.isNew || !target.ownsDeclaration) {
      // Either a tab beside a hand-written page, or the page of a division whose
      // declaration is hand-written: in both cases the route is a nav entry and a
      // matrix row, and nothing else is the maker's to write.
      paperworkPages.push({
        key: division.key,
        label: division.label,
        route: target.route,
        icon: division.icon,
      });
      continue;
    }

    const declared = [division.membership, ...(division.ranks ?? [])].filter(
      (role): role is NonNullable<typeof role> => Boolean(role),
    );

    // A role the registry already declares stays there: the generated file never
    // repeats a hand-written entry, because two copies of a snowflake is the
    // drift the registry exists to prevent.
    for (const role of declared) {
      if (!role.id || role.alias in ROLES) continue;
      if (roles.some((entry) => entry.alias === role.alias)) continue;
      roles.push({ alias: role.alias, name: role.name, id: role.id });
    }

    divisions.push({
      key: division.key,
      label: division.label,
      route: target.route,
      icon: division.icon,
      membershipAlias: division.membership?.alias,
      ranks: (division.ranks ?? []).map((rank) => rank.alias),
    });
  }

  return { roles, divisions, paperworkPages };
}

function generatedRolesContent(configs: readonly PaperworkConfig[]): string {
  const { roles, divisions, paperworkPages } = generatedRoles(configs);

  const roleEntries = roles
    .map(
      (role) =>
        `  ${JSON.stringify(role.alias)}: { id: ${JSON.stringify(
          role.id,
        )}, name: ${JSON.stringify(role.name)} },`,
    )
    .join("\n");

  const divisionEntries = divisions
    .map(
      (division) => `  ${JSON.stringify(division.key)}: {
    label: ${JSON.stringify(division.label)},
    route: ${JSON.stringify(division.route)},
${division.icon ? `    icon: ${JSON.stringify(division.icon)},\n` : ""}    ${division.membershipAlias ? `membership: ${JSON.stringify(division.membershipAlias)},` : ""}
    ranks: ${JSON.stringify(division.ranks)},
  },`,
    )
    .join("\n");

  const paperworkEntries = paperworkPages
    .map(
      (entry) => `  ${JSON.stringify(entry.key)}: {
    label: ${JSON.stringify(entry.label)},
    route: ${JSON.stringify(entry.route)},
${entry.icon ? `    icon: ${JSON.stringify(entry.icon)},\n` : ""}  },`,
    )
    .join("\n");

  return `// Generated by the Paperwork Maker. Do not edit by hand.
//
// Spread into \`ROLES\` and \`DIVISIONS\` in \`src/configs/roles.ts\` once; after
// that, a new division is one run of the maker and no edit to that registry.
import type { Division, GuildRoleEntry } from "@/configs/roles";

export const GENERATED_ROLES = {
${roleEntries}
} as const satisfies Record<string, GuildRoleEntry>;

export const GENERATED_DIVISIONS = {
${divisionEntries}
} as const satisfies Record<string, Division>;

/**
 * Pages of divisions the app already declares: either the division's paperwork
 * tab beside a hand-written page, or the page of a division that had none. The
 * division's own declaration stays in \`configs/roles.ts\`, so these are only a
 * sidebar entry and a matrix row.
 */
export const GENERATED_PAPERWORK_PAGES = {
${paperworkEntries}
} as const satisfies Record<
  string,
  { label: string; route: string; icon?: string }
>;
`;
}

function generatedPagesContent(configs: readonly PaperworkConfig[]): string {
  const entries = configs
    // A division declared by hand already has its artwork and links in a module;
    // this file only spells out the ones the maker introduced.
    .filter((config) => targetFor(config).ownsDeclaration)
    .map((config) => {
      const division = config.division;
      return `  ${JSON.stringify(division.key)}: {
    label: ${JSON.stringify(division.label)},
    image: ${JSON.stringify(division.emblem ?? "")},
    data: {
      image: ${JSON.stringify(division.image ?? "")},
      imageSize: ${JSON.stringify(division.imageSize ?? "150,150")},
      divisionName: ${JSON.stringify(division.label)},
      ranks: [],
      quickLinks: ${JSON.stringify(division.quickLinks ?? [])},
    },
  },`;
    })
    .join("\n");

  return `// Generated by the Paperwork Maker. Do not edit by hand.
//
// Spread into \`DIVISION_PAGES\` in \`src/app/constants/divisions/index.ts\`. The
// shape is spelled out rather than imported so this module has no cycle with the
// registry that consumes it.
export const GENERATED_DIVISION_PAGES = {
${entries}
} as const;
`;
}

/**
 * The emblems this checkout has, by file name without its extension: `AMU`,
 * `BLS`, `A&R - old`. Read from disk so the maker cannot offer a division an
 * image the repository does not hold.
 */
export async function readEmblemNames(
  options: { root?: string } = {},
): Promise<string[]> {
  const root = options.root ?? process.cwd();
  try {
    const entries = await readdir(path.join(root, EMBLEM_DIRECTORY));
    return entries
      .filter((entry) => /\.(png|jpe?g|svg|webp)$/i.test(entry))
      .map((entry) => entry.replace(/\.[^.]+$/, ""))
      .sort((a, b) => a.localeCompare(b));
  } catch {
    return [];
  }
}

/** Every generated config on disk, ordered by key - what the maker reopens. */
export async function readGeneratedConfigs(
  options: { root?: string } = {},
): Promise<PaperworkConfig[]> {
  const root = options.root ?? process.cwd();
  const keys = await existingGeneratedKeys(root);
  const configs: PaperworkConfig[] = [];

  for (const key of keys) {
    const raw = await readFromRoot(
      root,
      `${GENERATED_PAPERWORK_DIR}/${key}.json`,
    );
    if (!raw) continue;
    try {
      configs.push(JSON.parse(raw) as PaperworkConfig);
    } catch {
      // An unreadable config is skipped rather than shown half-edited.
    }
  }

  return configs;
}

/** Every generated config on disk, plus this one, ordered by key. */
async function plannedConfigs(
  root: string,
  config: PaperworkConfig,
): Promise<PaperworkConfig[]> {
  const keys = await existingGeneratedKeys(root);
  const others: PaperworkConfig[] = [];

  for (const key of keys) {
    if (key === config.division.key) continue;
    const raw = await readFromRoot(
      root,
      `${GENERATED_PAPERWORK_DIR}/${key}.json`,
    );
    if (!raw) continue;
    try {
      others.push(JSON.parse(raw) as PaperworkConfig);
    } catch {
      // A config that no longer parses is left alone rather than guessed at;
      // regenerating it is the fix, and the plan still preserves its file.
    }
  }

  return [...others, config].sort((a, b) =>
    a.division.key.localeCompare(b.division.key),
  );
}

/**
 * Every file this division needs, with the contents it would have. Validation
 * runs first: an unusable config produces problems and no files at all.
 */
export async function planDivision(
  config: PaperworkConfig,
  options: { root?: string } = {},
): Promise<PaperworkPlan> {
  const root = options.root ?? process.cwd();
  const validation = validatePaperworkConfig(config);
  if (!validation.ok) {
    return {
      ok: false,
      problems: validation.problems,
      files: [],
      integration: [],
    };
  }

  const key = config.division.key;
  const target = targetFor(config);
  const jsonPath = `${GENERATED_PAPERWORK_DIR}/${key}.json`;
  const configs = await plannedConfigs(root, config);

  const candidates: { path: string; content: string }[] = [
    { path: jsonPath, content: serialiseConfig(config) },
    {
      path: `${GENERATED_PAPERWORK_DIR}/index.ts`,
      content: aggregatorContent(configs.map((entry) => entry.division.key)),
    },
    { path: GENERATED_DIVISIONS_FILE, content: generatedRolesContent(configs) },
    {
      path: GENERATED_DIVISION_PAGES_FILE,
      content: generatedPagesContent(configs),
    },
    { path: target.pagePath, content: pageContent(config, key) },
  ];

  const files: PlannedFile[] = [];
  for (const candidate of candidates) {
    if (!isAllowedPath(candidate.path)) {
      return {
        ok: false,
        problems: [
          `Refusing to write ${candidate.path}: it is not a generated path.`,
        ],
        files: [],
        integration: [],
      };
    }

    const before = await readFromRoot(root, candidate.path);
    // A generated division whose page was hand-edited is not replaced: the maker
    // writes this file itself, so a different header means somebody owns it now.
    const foreignPage =
      candidate.path.endsWith("page.tsx") &&
      before !== undefined &&
      !before.startsWith("// Generated by the Paperwork Maker.");
    if (foreignPage) {
      return {
        ok: false,
        problems: [
          `${candidate.path} already exists and was not generated by the maker - it will not be overwritten.`,
        ],
        files: [],
        integration: [],
      };
    }

    files.push({
      path: candidate.path,
      content: candidate.content,
      before,
      action: fileAction(before, candidate.content),
    });
  }

  return {
    ok: true,
    problems: [],
    files,
    integration: [
      "src/configs/roles.ts - spread GENERATED_ROLES into ROLES and GENERATED_DIVISIONS into DIVISIONS (already wired once this slice is merged).",
      `src/app/constants/divisions/index.ts - spread GENERATED_DIVISION_PAGES, so ${divisionSlug(key)} has a division module when it is a new division.`,
      "src/components/layout/header/configs/HeaderLinks.ts - generated divisions and generated paperwork pages appear in the Divisions section.",
      "src/configs/access-matrix.ts - a row per generated route, so the Access Manager can narrow it.",
      "Grant the page in Access Manager: a generated route opens to every employee until its row is set.",
    ],
  };
}

export type PaperworkWrite = {
  written: string[];
  unchanged: string[];
  refused: string[];
};

/** Writes a plan, refusing anything that left the allowlist. */
export async function writePlan(
  plan: PaperworkPlan,
  options: { root?: string } = {},
): Promise<PaperworkWrite> {
  const root = options.root ?? process.cwd();
  const written: string[] = [];
  const unchanged: string[] = [];
  const refused: string[] = [];

  if (!plan.ok) return { written, unchanged, refused: ["the plan is not valid"] };

  for (const file of plan.files) {
    if (!isAllowedPath(file.path)) {
      refused.push(file.path);
      continue;
    }
    if (file.action === "unchanged") {
      unchanged.push(file.path);
      continue;
    }
    const full = path.join(root, file.path);
    await mkdir(path.dirname(full), { recursive: true });
    await writeFile(full, file.content, "utf8");
    written.push(file.path);
  }

  return { written, unchanged, refused };
}

/** Everything a generated route needs, for the nav and the matrix. */
export function generatedRouteEntries(config: PaperworkConfig): {
  route: string;
  label: string;
} {
  return {
    route: targetFor(config).route,
    label: config.division.label,
  };
}

